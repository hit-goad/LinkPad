package com.linkpad.controller

/** A conservative USB HID gamepad descriptor, carried by Android's Bluetooth HID Device profile. */
object GamepadReport {
    const val ID: Byte = 1
    // 16 buttons, hat switch, 4 signed 8-bit axes: LX, LY, RX, RY.
    val descriptor = intArrayOf(
        0x05, 0x01, 0x09, 0x05, 0xA1, 0x01, 0x85, ID.toInt(),
        0x05, 0x09, 0x19, 0x01, 0x29, 0x10, 0x15, 0x00, 0x25, 0x01, 0x95, 0x10, 0x75, 0x01, 0x81, 0x02,
        0x05, 0x01, 0x09, 0x39, 0x15, 0x00, 0x25, 0x07, 0x35, 0x00, 0x46, 0x3B, 0x01, 0x65, 0x14, 0x75, 0x04, 0x95, 0x01, 0x81, 0x42,
        0x75, 0x04, 0x95, 0x01, 0x81, 0x03,
        0x09, 0x30, 0x09, 0x31, 0x09, 0x33, 0x09, 0x34, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x04, 0x81, 0x02,
        0xC0
    ).map { it.toByte() }.toByteArray()

    fun encode(s: PadState): ByteArray = byteArrayOf(
        (s.buttons and 0xff).toByte(), ((s.buttons ushr 8) and 0xff).toByte(),
        s.hat.toByte(), s.lx.toByte(), s.ly.toByte(), s.rx.toByte(), s.ry.toByte()
    )
}

data class PadState(var buttons: Int = 0, var hat: Int = 8, var lx: Int = 0, var ly: Int = 0, var rx: Int = 0, var ry: Int = 0)
